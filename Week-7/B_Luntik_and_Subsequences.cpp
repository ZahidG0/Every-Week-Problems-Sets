ll power(ll p)
{
    ll ans = 1;

    while (p--)
    {
        ans *= 2;
    }

    return ans;
}

void ZH_Solve()
{
    int n;
    cin >> n;

    int cnt0 = 0, cnt1 = 0;

    for (int i = 0; i < n; i++)
    {
        ll x;
        cin >> x;

        if (x == 0)
            cnt0++;
        else if (x == 1)
            cnt1++;
    }

    ll ans = cnt1 * power(cnt0);

    cout << ans << nl;
}

